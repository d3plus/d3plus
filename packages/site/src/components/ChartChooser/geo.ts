/** How a column names US states. */
export type StateCode = "postal" | "name" | "fips";

const BY_CODE: Record<StateCode, Map<string, UsState>> = {
  postal: new Map(US_STATES.map(s => [s.postal, s])),
  name: new Map(US_STATES.map(s => [s.name.toLowerCase(), s])),
  fips: new Map(US_STATES.map(s => [s.fips, s])),
};

/** The state a value names in the given code, if any. */
export function findState(value: string, code: StateCode): UsState | undefined {
  const key =
    code === "postal"
      ? value.toUpperCase()
      : code === "name"
        ? value.toLowerCase()
        : value.padStart(2, "0");
  return BY_CODE[code].get(key);
}

/**
 * Whether every value is a country's ISO alpha-3 code (in capitals, as
 * datasets write them).
 */
export function isIso3(values: string[]): boolean {
  return values.length > 0 && values.every(v => v in ISO3_NUMERIC);
}

/**
 * The code a set of values names US states in: postal abbreviations, full
 * names, or FIPS codes (written as two-digit strings, so a column of small
 * numbers isn't mistaken for states). Undefined unless every value names one.
 */
export function stateCode(values: string[]): StateCode | undefined {
  if (!values.length) return undefined;
  if (values.every(v => /^[A-Z]{2}$/.test(v) && findState(v, "postal")))
    return "postal";
  if (values.every(v => /^\d{2}$/.test(v) && findState(v, "fips")))
    return "fips";
  if (values.every(v => findState(v, "name"))) return "name";
  return undefined;
}
